#!/usr/bin/env python3
"""
Generates app/src/assets/bodyMap.ts — the front/back body outline drawn on the exercise guide
page with the exercise's muscles highlighted — from the SVG paths in react-native-body-highlighter
(https://github.com/HichamELBSI/react-native-body-highlighter, MIT, (c) 2022 ELABBASSI Hicham).

Only the path data is used, not the package's component: its regions are regrouped under
free-exercise-db's muscle names (the vocabulary of primaryMuscles/secondaryMuscles), and its
single "upper-back" region is split so lats and the middle back can light up separately.

Run from the repo root with the package extracted somewhere (npm pack + tar xzf):

    python3 scripts/import-body-map.py path/to/package

The asset files are read as text (never executed): each `slug: "..."` starts a region and every
quoted string starting with M/m after it is one of its SVG paths, in file order (left then right).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "src" / "assets" / "bodyMap.ts"

# body-highlighter slug -> free-exercise-db muscles that light the region up. Regions mapped to
# [] (head, hands, knees, ...) are drawn as plain body. "hair" is dropped — it's drawn in the same
# grey as the head anyway.
SLUG_MUSCLES = {
    "abs": ["abdominals"],
    "obliques": ["abdominals"],
    "adductors": ["adductors"],
    "biceps": ["biceps"],
    "triceps": ["triceps"],
    "forearm": ["forearms"],
    "calves": ["calves"],
    "chest": ["chest"],
    "deltoids": ["shoulders"],
    "quadriceps": ["quadriceps"],
    "hamstring": ["hamstrings"],
    "neck": ["neck"],
    "lower-back": ["lower back"],
    # The drawing has no separate rhomboids — they sit under the trapezius' middle fibres, so the
    # back-view trapezius stands in for the middle back too.
    "trapezius": ["traps"],
    "trapezius@back": ["traps", "middle back"],
    # Glute medius/minimus, the main hip abductors, sit under/beside the glute max.
    "gluteal": ["glutes", "abductors"],
    "tibialis": [], "knees": [], "ankles": [], "feet": [], "hands": [], "head": [],
}

# "upper-back" paths in file order: left infraspinatus/teres minor, left lat, left teres major,
# then the same three on the right. Teres major ("the lat's little helper") goes with the lats.
UPPER_BACK_SPLIT = [
    ("middle back", [0, 3]),
    ("lats", [1, 2, 4, 5]),
]


def parse(asset: Path):
    regions = []  # [slug, [paths]]
    for line in asset.read_text().splitlines():
        m = re.search(r'slug:\s*"([^"]+)"', line)
        if m:
            regions.append([m.group(1), []])
            continue
        for d in re.findall(r'"([Mm][^"]+)"', line):
            regions[-1][1].append(d)
    return regions


def ts_regions(regions, side):
    out = []
    for slug, paths in regions:
        if slug == "hair":
            continue
        if slug == "upper-back":
            if len(paths) != 6:
                raise SystemExit(f"upper-back has {len(paths)} paths, expected 6 — re-check UPPER_BACK_SPLIT")
            for muscle, idx in UPPER_BACK_SPLIT:
                out.append(([muscle], [paths[i] for i in idx]))
            continue
        key = f"{slug}@{side}" if f"{slug}@{side}" in SLUG_MUSCLES else slug
        if key not in SLUG_MUSCLES:
            raise SystemExit(f"unmapped body-highlighter slug {slug!r} ({side})")
        out.append((SLUG_MUSCLES[key], paths))
    # Plain body first so highlighted regions are drawn on top.
    out.sort(key=lambda r: bool(r[0]))
    lines = []
    for muscles, paths in out:
        lines.append("  {\n    muscles: [%s],\n    paths: [\n%s\n    ],\n  },"
                     % (", ".join(f"'{m}'" for m in muscles), "\n".join(f"      '{p}'," for p in paths)))
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    assets = Path(sys.argv[1]) / "dist" / "assets"
    front = parse(assets / "bodyFront.js")
    back = parse(assets / "bodyBack.js")
    ts = (
        "// AUTO-GENERATED by scripts/import-body-map.py from the SVG paths in react-native-body-highlighter\n"
        "// (https://github.com/HichamELBSI/react-native-body-highlighter, MIT License,\n"
        "// Copyright (c) 2022 ELABBASSI Hicham). Do not hand-edit — re-run the script.\n"
        "//\n"
        "// Each region lists the free-exercise-db muscles (see MUSCLE_INFO in muscles.ts) that light it\n"
        "// up; regions with none are plain body. Plain regions come first so highlights draw on top.\n\n"
        "import { MuscleKey } from './muscles';\n\n"
        "export interface BodyRegion {\n"
        "  muscles: MuscleKey[];\n"
        "  paths: string[];\n"
        "}\n\n"
        "export const BODY_FRONT_VIEWBOX = '0 0 724 1448';\n"
        "export const BODY_BACK_VIEWBOX = '724 0 724 1448';\n\n"
        "export const BODY_FRONT: BodyRegion[] = [\n" + ts_regions(front, "front") + "\n];\n\n"
        "export const BODY_BACK: BodyRegion[] = [\n" + ts_regions(back, "back") + "\n];\n"
    )
    OUT.write_text(ts)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
